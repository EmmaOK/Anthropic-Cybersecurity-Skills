def main() -> int:
    parser = argparse.ArgumentParser(
        description="AI Agent Kill Switch and Graduated Response Agent",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    sub = parser.add_subparsers(dest="command", required=True)

    sc = sub.add_parser("scaffold", help="Generate kill switch files for an agent service")
    sc.add_argument("--agent-id", required=True, help="Agent identifier (e.g. ew-agent)")
    sc.add_argument("--port", type=int, default=8001, help="Agent's HTTP port")
    sc.add_argument("--output", default="./kill_switch_generated/", help="Output directory")

    si = sub.add_parser("simulate", help="Simulate signal combinations and show which level fires")
    si.add_argument("--signals", required=True,
                    help=f"Comma-separated signals. Valid: {', '.join(SIGNALS.keys())}")

    te = sub.add_parser("test", help="Test kill switch registration against a running agent")
    te.add_argument("--registry", required=True, help="Path to kill_registry.json")
    te.add_argument("--dry-run", action="store_true", help="Check only, do not trigger")

    au = sub.add_parser("audit", help="Audit a service directory for kill switch controls")
    au.add_argument("--service-path", required=True, help="Path to the agent service directory")

    args = parser.parse_args()
    dispatch = {
        "scaffold": cmd_scaffold,
        "simulate": cmd_simulate,
        "test": cmd_test,
        "audit": cmd_audit,
    }
    return dispatch[args.command](args)


if __name__ == "__main__":
    sys.exit(main())
