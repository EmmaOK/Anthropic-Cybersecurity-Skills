"""
AI Agent Kill Switch and Graduated Response Agent

Scaffolds, tests, and simulates the three-level graduated containment response
system for AI agents.

Subcommands:
  scaffold  — Generate kill switch implementation files for an agent service
  test      — Test a kill switch against a running agent (staging use only)
  simulate  — Simulate graduated response signal combinations and show which
              level fires
  audit     — Audit an existing agent service for kill switch readiness

Usage:
    agent.py scaffold --agent-id ew-agent --port 8001 --output ./generated/
    agent.py test     --registry /var/run/agent/kill_registry.json --dry-run
    agent.py simulate --signals injection_high,external_endpoint_called
    agent.py audit    --service-path ./ew-agent/

Exit codes:
    0 — kill switch present and test passed / simulation non-critical
    1 — kill switch absent, test failed, or Level 3 dual signal confirmed
"""

